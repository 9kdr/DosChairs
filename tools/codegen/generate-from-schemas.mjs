#!/usr/bin/env node
/**
 * Records which JSON schemas are the source of truth.
 * Hand-written TS/Rust/Python types must stay aligned with these files.
 * A full emitter can replace this once the IR stabilizes.
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const schemaDir = path.join(root, "schemas");
const outFile = path.join(root, "packages/shared/src/schema-ids.ts");

const names = (await readdir(schemaDir)).filter((n) => n.endsWith(".schema.json")).sort();
const body = `/* Generated by tools/codegen/generate-from-schemas.mjs. Do not edit. */
export const schemaIds = ${JSON.stringify(names, null, 2)} as const;

export type SchemaId = (typeof schemaIds)[number];
`;

await writeFile(outFile, body);
console.log(`wrote ${path.relative(root, outFile)} (${names.length} schemas)`);
