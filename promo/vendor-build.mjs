// Regenerates vendor/sleepy-scene.js from the app's sleepy-chair pixel banner (#317).
import { stripTypeScriptTypes } from "node:module";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
const here = import.meta.dirname;
const src = readFileSync(join(here, "../apps/desktop/src/components/sleepy-chair/scene.ts"), "utf8");
const js = stripTypeScriptTypes(src).replace(/^export\s+/gm, "");
mkdirSync(join(here, "vendor"), { recursive: true });
writeFileSync(join(here, "vendor/sleepy-scene.js"), `// Generated by vendor-build.mjs from apps/desktop/src/components/sleepy-chair/scene.ts.\n(() => {\n${js}\nwindow.SleepyScene = { createScene, step, render };\n})();\n`);
console.log("wrote vendor/sleepy-scene.js");
